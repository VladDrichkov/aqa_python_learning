## Задание 4. Отчёт по статусам
# Дан список результатов прогона.
# Посчитать, сколько тестов в каждом статусе и сколько разных статусов встретилось.

results = ["пройден", "провален", "пройден", "пропущен", "пройден", "провален"]

tests_report = {}
for result in results:
     tests_report[result] = tests_report.get(result, 0) + 1

print(tests_report)
print(f"total statuses: {len(tests_report)}")

