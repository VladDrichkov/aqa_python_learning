## Задание 2. Палиндром
# Напиши функцию: принимает слово, возвращает `True`, если оно читается одинаково в обе стороны.
#
# Проверь на «шалаш», «довод» и «питон».
print("==============## Задание 2. Палиндром===========")

def is_palindrome(name):
    if type(name) == str:
        return name == name[::-1]
    else:
        return None

print(is_palindrome("шалаш"))
print(is_palindrome("довод"))
print(is_palindrome("питон"))

